"""Pack exactly C's Float32 source geometry and original colour texels; no donor assets."""
import argparse,gzip,hashlib,json,struct
from pathlib import Path
from PIL import Image
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--export',type=Path,required=True)
p.add_argument('--out',type=Path,required=True)
p.add_argument('--index',type=Path,required=True)
a=p.parse_args()
D=a.export
p=D/'three-buffer-export.json'; fixed='7740ddc9ea558ae99b15f2d94221478f1f7ba71603701cf2333c490a27d24854'
assert hashlib.sha256(p.read_bytes()).hexdigest()==fixed, 'not exact reviewed C mesh'
o=json.loads(p.read_bytes()); r=bytearray(struct.pack('<4sHHII',b'RAIL',1,len(o['data']),0,0))
parts=[]
source_png={
 'stucco.png':'e284425a67cd0484508d83646218a23ed0e0ec7e62ae69edeada336e0a413a45',
 'roof.png':'8882ea2ae3b466a1b91c66c3f5fa1ea01172345e681d05d60402532bfe135006',
 'timber.png':'f57338e6494ebe15616627f21788f8019c16f3600ec5714aba3de8622edfe91f',
 'brick.png':'2f798d19597f484cc3a398cf0cfeb78bf6af299c991d327122e3c2627d821a6a',
}
for j,g in enumerate(o['data']):
    nv=len(g['xyz'])//3; ni=len(g['ix']); assert len(g['xyz'])==3*nv and len(g['normal'])==3*nv and len(g['uv'])==2*nv and len(g['tone'])==3*nv and ni%3==0
    assert max(g['ix'])<nv<65536
    source=o['palette'][g['name']]
    s=256 if source.get('src') else 0
    r+=struct.pack('<HHIII',j,nv,ni,s,0)
    for k in ('xyz','normal','uv','tone'):
        r+=struct.pack(f"<{len(g[k])}f",*g[k])
    r+=struct.pack(f'<{ni}H',*g['ix'])
    if ni%2:r+=b'\0\0'
    assert len(r)%4==0
    if s:
        p=D/source['src']
        assert hashlib.sha256(p.read_bytes()).hexdigest()==source_png[p.name]
        t=Image.open(p).convert('RGBA')
        assert t.size==(s,s)
        r+=t.transpose(Image.Transpose.FLIP_TOP_BOTTOM).tobytes()
    part={'name':g['name'],'nv':nv,'ni':ni,'textureSize':s,'rgb':source['colour'],'rough':source['roughness'],'metal':source['metalness']}
    if s:part['repeat']=source['scale']
    parts.append(part)
struct.pack_into('<I',r,8,len(r))
compress=gzip.compress(r,compresslevel=9,mtime=0)
name='summerside-station-C-v1.bin.gz'
a.out.write_bytes(compress)
asset={'file':name,'raw':len(r),'wire':len(compress),'rawSha':hashlib.sha256(r).hexdigest(),'wireSha':hashlib.sha256(compress).hexdigest(),'triangles':sum(p['ni']//3 for p in parts),'parts':parts,'authorFreeze':fixed}
a.index.write_text('// Exact reviewed C, generated by tools/art/summerside-station/pack.py; original numerical content only.\nexport const RAIL_ART='+json.dumps(asset,indent=1)+' as const;\n')
print({k:v for k,v in asset.items()if k!='parts'})
