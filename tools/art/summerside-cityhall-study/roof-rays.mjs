import * as T from 'three';
import fs from 'node:fs';
import {buildCityHall,y} from './src/cityhall-model.ts';
if(!process.argv[2])throw new Error('Pass a registered native witness JSON as generated by make-witness.py.');
const {model}=buildCityHall(false);model.updateMatrixWorld(true);const src=JSON.parse(fs.readFileSync(process.argv[2]));
const ray=new T.Raycaster();const reports={};
const quant=(a,p)=>{const q=a.slice().sort((a,b)=>a-b);return q[Math.round((q.length-1)*p)];};
for(const [k,pts] of Object.entries(src)){
 let miss=0;let hit=[];
 for(const [x,z,e] of pts){
  ray.set(new T.Vector3(x,60,z),new T.Vector3(0,-1,0));const c=ray.intersectObject(model,true)[0];if(!c){miss++;continue;}
  const error=c.point.y-y(e);hit.push({x,z,e,err:error,abs:Math.abs(error),hit:c.object.name});
 }
 const err=hit.map(a=>a.abs);
 reports[k]={count:pts.length,miss,nearP50:quant(err,.5),p90:quant(err,.9),max:quant(err,1),distinction:Object.fromEntries([...new Set(hit.map(v=>v.hit))].map(z=>[z,hit.filter(v=>v.hit===z).length])),worst:hit.sort((a,b)=>b.abs-a.abs).slice(0,10)};
}
fs.mkdirSync('proof',{recursive:true});fs.writeFileSync('proof/actual-ray-witness.json',JSON.stringify(reports,null,2));
for(const [k,{count,miss,p90,distinction}]of Object.entries(reports))console.log(k,{count,miss,p90,distinction});
