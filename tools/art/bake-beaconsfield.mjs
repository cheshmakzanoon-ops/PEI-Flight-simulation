// Only the original, owner-clipped render art is archived. No donor image
// or classified LiDAR point is emitted. Run at repository root:
// node --experimental-strip-types tools/art/bake-beaconsfield.mjs
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {beaconsfieldPaints} from '../../src/render/beaconsfield-review-material.ts';
import {makeBeaconsfieldPreview} from './beaconsfield-plan.ts';
const began=performance.now(),model=makeBeaconsfieldPreview();
if(!model)throw new Error('Owner polygon/mesh gate failed');
const batches=[];
for(const mesh of model.children){
 const g=mesh.geometry,fields=['position','normal','uv'],arrays=fields.map(f=>g.getAttribute(f).array),
   bits=arrays.map(a=>new Uint32Array(a.buffer,a.byteOffset,a.length)), count=arrays[0].length/3;
 if(!count)continue;
 const name=mesh.name.replace(/^inside-outline closure: /,''), id=beaconsfieldPaints.indexOf(name), closure=Number(name!==mesh.name);
 if(id<0||!Number.isInteger(count)||count%3)throw new Error('Invalid original geometry schema');
 const look=new Map(),verts=[],indices=[];
 for(let i=0;i<count;i++){
  const a=i*3,b=i*2;
  const key=[bits[0][a],bits[0][a+1],bits[0][a+2],bits[1][a],bits[1][a+1],bits[1][a+2],bits[2][b],bits[2][b+1]].join(',');
  let index=look.get(key);if(index===undefined){index=look.size;look.set(key,index);verts.push(i);}
  indices.push(index);
 }
 if(verts.length>65535)throw new Error('Baked batch too dense');
 const header=Buffer.alloc(12);header.writeUInt16LE(id,0);header.writeUInt16LE(closure,2);header.writeUInt16LE(verts.length,4);header.writeUInt32LE(indices.length,8);
 const data=Buffer.alloc(32*verts.length+((indices.length*2+3)&~3));
 let at=0;
 for(let k=0;k<arrays.length;k++)for(const i of verts){const n=k===2?2:3;for(let c=0;c<n;c++){data.writeUInt32LE(bits[k][n*i+c],at);at+=4;}}
 for(const i of indices){data.writeUInt16LE(i,at);at+=2;}
 batches.push({id,name,closure,indexCount:indices.length,vertexCount:verts.length,header,data});
}
const header=Buffer.alloc(16);header.write('BEA1',0,'ascii');header.writeUInt16LE(batches.length,4);
header.writeUInt16LE(1,6);header.writeUInt32LE(16+batches.reduce((n,g)=>n+g.header.length+g.data.length,0),8);
const flat=Buffer.concat([header,...batches.flatMap(g=>[g.header,g.data])]),gzip=gzipSync(flat,{level:9});
const sha=a=>createHash('sha256').update(a).digest('hex');
const stamp={file:'beaconsfield-v1.bin.gz',compressedBytes:gzip.length,decodedBytes:flat.length,compressedSha256:sha(gzip),decodedSha256:sha(flat),minimumInsetMetres:model.userData.minimumPlanInsetM,triangles:model.userData.triangles,batches:batches.length,uniqueVertices:batches.reduce((s,b)=>s+b.vertexCount,0)};
const moduleSource='// Generated by tools/art/bake-beaconsfield.mjs, original geometry only.\nexport const BEACON_ASSET='+JSON.stringify(stamp)+' as const;\n';
const paths=['public/art/'+stamp.file,'src/render/beaconsfield-review-asset.ts'];
if(process.argv.includes('--verify')){
 if(!readFileSync(paths[0]).equals(gzip)||readFileSync(paths[1],'utf8')!==moduleSource)throw Error('Published Beaconsfield assets do not match original bake');
}else{
 mkdirSync('public/art',{recursive:true});
 writeFileSync(paths[0],gzip);
 writeFileSync(paths[1],moduleSource);
}
console.log(JSON.stringify({stamp,bakeMs:performance.now()-began,groups:batches.map(({name,closure,indexCount,vertexCount})=>({name,closure,indexCount,vertexCount}))},null,2));
