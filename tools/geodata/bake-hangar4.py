#!/usr/bin/env python3
"""Reproduce the single Hangar 4 shell from the pinned NRCan 1 m DSM/DTM."""
import argparse
from pathlib import Path
import subprocess
import sys

HEADER = '// Generated by the bounded Hangar 4 OGL survey fit. Does not include photography.\n'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--scratch', type=Path, required=True)
    parser.add_argument('--reuse-window', action='store_true',
                        help='Skip network read and reuse native.json and native.npz emitted by the same pinned read.')
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    root = args.root.resolve()
    scratch = args.scratch.resolve()
    scratch.mkdir(parents=True, exist_ok=True)
    steps = ('fit.py', 'partition.py', 'bake-hangar.py', 'holdout.py')
    if not args.reuse_window:
        steps = ('native.py', *steps)
    for name in steps:
        subprocess.run([sys.executable, str(Path(__file__).parent/'hangar4'/name),
                        str(scratch), str(root)], check=True)
    payload = (scratch/'hangar-baked.json').read_text().rstrip('\n')
    result = HEADER + 'export const HANGAR4=' + payload + ' as const;\n'
    if args.verify and result != (root/'src/render/hangar4.generated.ts').read_text():
        raise SystemExit('Rebuilt Hangar 4 payload did not match the checked module.')
    (scratch/'hangar4.generated.ts').write_text(result)
    print(f'Hangar 4 shell and spatial holdout in {scratch}')

if __name__ == '__main__':
    main()
