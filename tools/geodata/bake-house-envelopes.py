#!/usr/bin/env python3
"""Bake supported roof-plane attributes; keep the separate OSM classification extract ODbL."""
from pathlib import Path
from hashlib import sha256
from collections import Counter,defaultdict
import argparse,gzip,json,math
import numpy as np
P=argparse.ArgumentParser(description=__doc__)
P.add_argument('--root',required=True,type=Path);P.add_argument('--source',type=Path,required=True);P.add_argument('--out',type=Path);A=P.parse_args()
src=A.source;root=A.root
idx=json.loads((root/'public/world/buildings/index.json').read_text())
pack=(root/'public/world/buildings/tiles.pack').read_bytes()
assert sha256(pack).hexdigest()==idx['sha256']
farm=(root/'src/render/farm-shells.generated.ts').read_text()
other=json.loads(farm.split('export const FARM_PROFILES=',1)[1].split(' as const')[0])
farmIDs={(t,d[0])for t,rows in other.items()for d in rows}
AT={}
def shape(tile,offset):
 if tile not in AT:
  k=next(k for k in idx['tiles']if k['id']==tile)
  AT[tile]=json.loads(gzip.decompress(pack[k['offset']:k['offset']+k['bytes']]))['features']
 return AT[tile][offset]
geoM=6378137*math.pi/180;quad=1-.00669437999014*math.sin(math.radians(46.5))**2
scale=np.array([geoM*math.cos(math.radians(46.5))/math.sqrt(quad),-geoM*(1-.00669437999014)/quad**1.5])
origin=np.array([-63.2,46.5])
fits=json.loads((src/'residential-shapes.json').read_text())
sets=defaultdict(list);metas=[];odbl=[];variant=Counter()
def fpkey(r):
 h=2166136261
 for a in r:
  for y in a:h=((h^round(y*1e6))*16777619)&0xffffffff
 return h
for v in sorted(fits,key=lambda r:(r['tile'],r['i'])):
 t,j=v['tile'],v['i']
 if (t,j) in farmIDs:continue
 source=shape(t,j);assert source['footprint']==v['fp']
 xz=(np.array(v['fp'])-origin)*scale
 C=xz.mean(0);a=(xz+np.roll(xz,-1,axis=0))*.5;B=np.roll(xz,-1,axis=0)
 lens=np.linalg.norm(B-xz,axis=1)
 normal=lambda p:p/np.maximum(1e-6,np.linalg.norm(p,axis=1))[:,None]
 score=np.sum(normal(a-C)*normal(np.array(v['roadPoint'])-a),axis=1)+.10*np.clip(lens/7.0,0.,1.)
 score[lens<4.7]=-10
 planes=np.asarray(v['planes']);y=np.min(np.c_[np.ones(len(a)),a-C]@planes.T,axis=1)
 score[y<2.70]=-10
 face=int(np.argmax(score)) if score.max()>.42 else -1
 tagged=v.get('osmMatch',{}).get('tags',{})
 try:levels=int(float(tagged.get('building:levels','0')))
 except ValueError:levels=0
 levels=levels if levels in (1,2) else 0
 maximum_slope=np.linalg.norm(planes[:,1:],axis=1).max()
 family=10 if maximum_slope>.67 else (12 if v['kind']=='hip' or v['area']>=180 else 11)
 plane=np.rint(planes*np.array([1000,1e6,1e6])).astype(int).ravel().tolist()
 tok=fpkey(source['footprint'])
 sets[t].append([j,tok,family,face,levels,*plane])
 variant[family]+=1
 metas.append(dict(tile=t,i=j,hash=v['windowSHA'],n=v['n'],hold=v['nHold'],kind=v['kind'],city=v['city'],county=v['county'],
   footprintKey=tok,p90=v['p90'],oldP90=v['olderP90'],datum=v['datum'],context='OSM' if 'osmMatch'in v else 'CLUI'))
 if 'osmMatch'in v:
  use=v['osmMatch']
  types={k:val for k,val in tagged.items() if k in ('building:levels','roof:shape')}
  odbl.append(dict(osm=use['osm'],building=use['bucket'],outline=use['outline'],tags=types,tile=t,i=j,
      intersectionOverUnion=round(v['osmIoU'],7),centreDistanceM=round(v['osmCenterDelta'],5),matchBasis=v['mappingBasis']))
emit=lambda d:json.dumps(d,separators=(',',':'))
B="\n".join(["// Source-bound house envelopes, generated by bake-house-envelopes.py. Do not hand edit.",
 "export const HOME_ATLAS_SHA="+json.dumps(idx['sha256'])+";",
 "export const HOME_COUNT="+str(len(metas))+";",
 "export const HOME_FORMS={",',\n'.join(' '+json.dumps(k)+':'+emit(v)for k,v in sets.items()),"} as const;",""])
(A.out or root/'src/render/home-envelopes.generated.ts').write_text(B)
print(len(metas),dict(Counter(x['county'] for x in metas)),dict(Counter(x['city'] for x in metas)),len(sets),'tiles',variant)
print(len(B), len(gzip.compress(B.encode(),mtime=0)),len(odbl),'ODbL records')
(src/'rendered-house-targets.json').write_text(emit(metas)+'\n')
(src/'osmdb-house-support.json').write_text(emit(odbl)+'\n')
