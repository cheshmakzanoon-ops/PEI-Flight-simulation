// Rebuild exact centre-of-stem exclusions from the checked-in source atlases. Offline, deterministic.
//   node --experimental-strip-types tools/geodata/bake-tree-clearance.ts [--check]
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {gunzipSync} from 'node:zlib';
import {project} from '../../src/sim/geo.ts';
import {Terrain} from '../../src/sim/terrain.ts';
import {Cover} from '../../src/sim/cover.ts';
import {runwayAt} from '../../src/sim/places.ts';
import {TREE_PITCH,treeRandom,treeCellKey} from '../../src/sim/tree-layout.ts';
type P={x:number;z:number};
type Coord=[number,number];
type Ring=P[];
type Feature={footprint:Coord[];holes?:Coord[][]};
const world=new URL('../../public/world/',import.meta.url);
const result=new URL('../../src/sim/tree-clearance.generated.ts',import.meta.url);
const read=(f:string)=>readFileSync(new URL(f,world));
const sha=(buf:Uint8Array)=>createHash('sha256').update(buf).digest('hex');
export function insideRing(x:number,z:number,ring:Ring){
  let inside=false;
  for(let i=0,j=ring.length-1;i<ring.length;j=i++){
    const a=ring[j],b=ring[i];
    if((a.z>z)!==(b.z>z)&&x<(b.x-a.x)*(z-a.z)/(b.z-a.z)+a.x)inside=!inside;
  }
  return inside;
}
/** Courtyards are holes in the roof footprint, not implicit clearance zones. */
export function insideRoof(x:number,z:number,outer:Ring,holes:Ring[]){
  return insideRing(x,z,outer)&&!holes.some(h=>insideRing(x,z,h));
}
export function bake(){
  const index=JSON.parse(read('buildings/index.json').toString());
  const pack=read('buildings/'+index.file);
  if(sha(pack)!==index.sha256)throw Error('Roof archive digest differs from source manifest.');
  const tm=JSON.parse(read('terrain.json').toString()),terrainBytes=read(tm.file);
  const raw=gunzipSync(terrainBytes);
  const terrain=new Terrain(tm,new Int16Array(raw.buffer,raw.byteOffset,raw.byteLength/2));
  const cm=JSON.parse(read('cover.json').toString()),coverBytes=read(cm.file);
  const cover=new Cover(cm.width,cm.height,gunzipSync(coverBytes));
  const keys=new Set<number>(),tileSet=new Set<number>();let roofs=0,roofsHit=0,insideHits=0,holesSeen=0;
  for(const tile of index.tiles){
    const features:Feature[]=JSON.parse(gunzipSync(pack.subarray(tile.offset,tile.offset+tile.bytes)).toString()).features;
    for(const feature of features){
      roofs++;
      const toWorld=(r:Coord[])=>r.map(([lon,lat])=>project(lon,lat));
      const ring=toWorld(feature.footprint),holes=(feature.holes??[]).map(toWorld);
      holesSeen+=holes.length;if(ring.length<3)continue;
      let xmin=Infinity,xmax=-Infinity,zmin=Infinity,zmax=-Infinity,occupied=false;
      for(const p of ring){xmin=Math.min(xmin,p.x);xmax=Math.max(xmax,p.x);zmin=Math.min(zmin,p.z);zmax=Math.max(zmax,p.z);}
      for(let j=Math.floor(zmin/TREE_PITCH);j<=Math.floor(zmax/TREE_PITCH);j++){
        for(let i=Math.floor(xmin/TREE_PITCH);i<=Math.floor(xmax/TREE_PITCH);i++){
          const x=(i+treeRandom(i,j,11))*TREE_PITCH,z=(j+treeRandom(i,j,84))*TREE_PITCH;
          if(x<xmin||x>xmax||z<zmin||z>zmax||!insideRoof(x,z,ring,holes))continue;
          if(cover.sample(terrain,x,z)!==10||!terrain.isLand(x,z)||runwayAt(x,z))continue;
          const key=treeCellKey(i,j);
          if(key<0)throw Error('Grow clearance coordinates before changing province extent.');
          insideHits++;occupied=true;keys.add(key);tileSet.add(Math.floor(key/256));
        }
      }
      if(occupied)roofsHit++;
    }
  }
  if(roofs!==index.count)throw Error('Missing building records.');
  const sorted=[...keys].sort((a,b)=>a-b);
  // LEB128 deltas usually fit one or two bytes because the ordering groups neighboring cells.
  const bytes:number[]=[];let last=0;
  for(const k of sorted){
    let n=k-last;last=k;
    while(n>=128){bytes.push((n%128)+128);n=Math.floor(n/128);}
    bytes.push(n);
  }
  const delta=Buffer.from(bytes),b64=delta.toString('base64'),segments=b64.match(/.{1,120}/g)??[''];
  const tally={sourceRoofs:roofs,sourceHoles:holesSeen,footprintsWithStems:roofsHit,stemRoofPairs:insideHits,
    uniqueStems:sorted.length,tilesWithBlockedStems:tileSet.size,deltaBytes:delta.byteLength};
  const header=[
    '// GENERATED by tools/geodata/bake-tree-clearance.ts. Do not hand-edit.',
    '// Source data: NRCan Automatically Extracted Buildings PEI 2020 (OGL-Canada),',
    '// ESA WorldCover 2021 (CC BY 4.0); terrain & shoreline credits: docs/WORLD.md.',
    '// Sorted, delta-coded generator cells only, no runtime imagery or personal data.',
    '// Inputs (SHA-256): building pack '+sha(pack),
    '// cover '+sha(coverBytes)+' | height '+sha(terrainBytes),
    '// '+JSON.stringify(tally),
    'export const roofCellCount='+sorted.length+';',
    'export const roofCellDeltas=',
  ].join('\n');
  return {tally,sorted,text:header+'\n'+segments.map((s,i)=>"  '"+s+"'"+(i===segments.length-1?';':'+')).join('\n')+'\n'};
}
if(process.argv[1]&&pathToFileURL(resolve(process.argv[1])).href===import.meta.url){
  const {tally,text}=bake();
  if(process.argv.includes('--check')){
    if(readFileSync(result,'utf8')!==text)throw Error('Stale tree clearance; rerun the baker and review source changes.');
  }else writeFileSync(result,text);
  console.log(JSON.stringify(tally),fileURLToPath(result));
}
