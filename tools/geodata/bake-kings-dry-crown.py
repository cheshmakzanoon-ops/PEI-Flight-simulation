#!/usr/bin/env python3
"""Bake the single predeclared dry crown from 2 m separated 2020 training only.
Run from a separate working dir with Python GDAL/SciPy, after raw-grid/actual-core/dry-scope/stock-nodes.
Unseen odd-index native 1 m sample heights never enter the target field.
"""
from pathlib import Path
import argparse,gzip,hashlib,json,math
import numpy as np
from osgeo import osr
from scipy.ndimage import distance_transform_edt,map_coordinates
D=Path('.')
cli=argparse.ArgumentParser(description=__doc__);cli.add_argument('--out',type=Path,required=True,help='scratch tree for regenerated runtime assets and source stamp')
output=cli.parse_args().out.resolve()
I=json.loads((D/'owner-grid.json').read_text()); S=json.loads((D/'dry-2112-source.json').read_text());
A=np.load(D/'dry-2112-native.npz');C=np.load(D/'dry-scope-fields.npz')
raw=A['dtm'].astype('f8'); native=np.where(raw>-100,raw,-10000)
if hashlib.sha256(A['dsm'].astype('<f4').tobytes()+A['dtm'].astype('<f4').tobytes()).hexdigest()!=S['rawSha256']: raise RuntimeError('Morph source crop changed')
G=np.fromfile(D/'stock-nodes.f64','<f8').reshape(*I['shape'],6)
x,z,old,phy,cover,cls=G.transpose(2,0,1)
rad=math.pi/180.; lon0,lat0=-63.2,46.5; e2=6.69437999014e-3; phi=rad*lat0; T=1-e2*math.sin(phi)**2
mx=6378137*rad*math.cos(phi)/math.sqrt(T); mz=-6378137*(1-e2)*rad/T**1.5
ll=np.stack([lon0+x/mx,lat0+z/mz],axis=-1)
def sr(k):
 r=osr.SpatialReference();r.ImportFromEPSG(k);r.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER);return r
m=osr.CoordinateTransformation(sr(4326),sr(3979)); p=np.asarray(m.TransformPoints(ll.reshape(-1,2).tolist()))[:,:2].reshape(*I['shape'],2)
a,b=S['pixelEdges']; c=(p[...,0]-a-.5); r=(b-p[...,1]-.5)
f=map_coordinates(native[::2,::2],[r*.5,c*.5],order=1,mode='constant',cval=-10000)
# Full incident-triangle support around nonzero vertices: the 1.700 × 1.635 m
# lattice diagonal is <2.36 m. A 5 m measured-interior admission leaves space
# for repositioning through the native affine and byte quantization around it.
Y,X=np.indices(raw.shape)
train=map_coordinates(native[::2,::2],[Y*.5,X*.5],order=1,mode='constant',cval=-10000)
safe=C['allow']&(train>1.45)
margin=map_coordinates(distance_transform_edt(safe),[r,c],order=1,mode='constant',cval=0)
def smooth(u):
 p=np.clip(u,0,1);return p*p*(3-2*p)
# Domain declared from reviewer-screened crown and near actor guards, not the
# withheld elevations. Only the underlying 36m transition tapers to old grade.
w=(1-smooth((abs(x-32170)-54)/36))*(1-smooth((abs(z-6936)-25)/36))*smooth((margin-5.0)/13.5)
weight=np.floor(w*255+1e-7).astype(np.uint8)
weight[w>1-1e-12]=255
move=np.rint((f-old)*weight/255.*100).astype('<i2');nz=weight>0
border=np.zeros(x.shape,dtype=bool);border[[0,-1],:]=True;border[:,[0,-1]]=True
assert not (weight[border].any() or move[border].any() or move[~nz].any())
assert (cover[nz]>70).all() and (f[nz]>1.45).all() and (margin[nz]>5).all() and (cls[nz]!=10).all()
assert ((move[nz]>=-1250)&(move[nz]<=1250)).all()
# Check actual projected triangles that can carry any support against native
# conservative allowance. Certify with nearest full native-mask sample minus
# half-diagonal (source pixel corners), not merely node eligibility.
from scipy.ndimage import binary_dilation
active=binary_dilation(nz,structure=np.ones((3,3),bool))
guard=map_coordinates(distance_transform_edt(safe),[r,c],order=0,mode='constant',cval=0)
assert float(guard[active].min())>2.4 and float(cover[active].min())>69.
bytes_=move.tobytes()+weight.tobytes();packed=gzip.compress(bytes_,compresslevel=9,mtime=0)
sha=lambda b:hashlib.sha256(b).hexdigest()
file='coastal/dry-v1/kings-crown-2020.g11.gz'; dest=output/'public/world'/file;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(packed)
profile={**I['spec'],'file':file,'sha256':sha(bytes_),'wireBytes':len(packed),'wireSha':sha(packed),'decodedBytes':len(bytes_),
 'terrainSha256':I['decodedTerrainSha'],'coverCompressedSha256':'46a4f4736a885576fa0529cd0f91bacdbfd47e3bfd719130ba3446c52c245863','coverDecodedSha256':I['decodedCoverSha'],
 'roadsSha256':'72528a1b26b68ee345e5047f30f2c9b49a3c18edeaccaf3e759ead296d3276c1',
 'sidewalksSha256':'e2dce7c86c4b5cd45ea45fb92ed89c2ae504306e4349e1291e627a669630e384',
 'parkingSha256':'071f8b599e27afcda8a1924cb152135f342c47756de1667fea28c0fdbb294303',
 'hedgeIndexSha256':'601cb33036c694028dc1c04f0107263108d9d786218f69ace58fdb2798f09f2a',
 'boundsXZ':[float(x[nz].min()-I['step'][0]),float(z[nz].min()-I['step'][1]),float(x[nz].max()+I['step'][0]),float(z[nz].max()+I['step'][1])]}
generated=output/'src/sim/kings-dry-crown.generated.ts';generated.parent.mkdir(parents=True,exist_ok=True)
generated.write_text('// Generated by tools/geodata/bake-kings-dry-crown.py. Fixed NRCan 2020 training split.\nexport const KINGS_DRY_CROWN=Object.freeze('+json.dumps(profile,indent=1)+' as const);\n')
receipt={'stamp':profile,'nativeScope':S,'maximumMoveM':float(np.max(abs(move))*.01),'minSignedCoverAtInfluenceNodes':float(cover[active].min()),'minimumNativeReserveAtInfluenceNodes':float(guard[active].min()),
 'nonzeroSupportVertices':int(nz.sum()),'fullWeightVertices':int((weight==255).sum()),'exactNativeOutsideFitHoldPattern':'All 1 m raster centres except source row and column both even. Collider and visual grade blend are not extra survey facts.',
 'rectangle':[float(x.min()),float(z.min()),float(x.max()),float(z.max())], 'registeredPins':['cover','terrain','decoded roads','verified building index','decoded sidewalks','decoded parking','hedge directory']}
(D/'crown-pack-receipt.json').write_text(json.dumps(receipt,indent=2)+'\n');print(json.dumps(receipt,indent=2))
