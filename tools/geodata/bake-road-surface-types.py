#!/usr/bin/python3
"""Read official NRN roadway surface attributes without changing ribbon geometry."""
import argparse,base64,gzip,hashlib,importlib.util,json,struct
from collections import Counter
from pathlib import Path
from osgeo import ogr,osr
ogr.UseExceptions()

def run(source,root):
    with source.open('rb') as f:
        assert hashlib.file_digest(f,'sha256').hexdigest()=='47dbfc17f20846fc1f077e214d0e6ac3f2676dfa2f79b754a2cd941e768a7e6a'

    m=json.loads((root/'public/world/roads.json').read_text())
    packed=gzip.decompress((root/'public/world/roads.bin.gz').read_bytes())
    assert hashlib.sha256(packed).hexdigest()==m['sha256']
    magic,version,count=struct.unpack_from('>4sHI',packed)
    assert (magic,version,count)==(b'PEIR',1,19465)
    f=Path(__file__).with_name('build_roads.py')
    loader=importlib.util.spec_from_file_location('build',f);mod=importlib.util.module_from_spec(loader);loader.loader.exec_module(mod)
    ds=ogr.Open(str(source))
    layer=ds.GetLayerByName(m['layer'])
    src=layer.GetSpatialRef();src.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    dst=osr.SpatialReference();dst.ImportFromEPSG(4326);dst.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    trans=osr.CoordinateTransformation(src,dst)
    offset=10;ordinal=0;bitset=bytearray((count+7)//8);summary=Counter()
    routes={}
    for f in layer:
        geom=f.GetGeometryRef().Clone();geom.Transform(trans);geom=geom.Simplify(.000022)
        points=[]
        for x,y,*_ in geom.GetPoints():
            q=round((x+65)*1e5),round((y-45)*1e5)
            if not points or points[-1]!=q:points.append(q)
        if len(points)<2:continue
        # Verify each geometry sequence and base flags, not just its ordinal or surface label.
        flags=mod.CLASSES.get(f['ROADCLASS'],0)
        if f['PAVSTATUS']=='Paved':flags|=8
        if f['STRUCTTYPE']=='Bridge':flags|=16
        data=struct.pack('>HB',len(points),flags)+b''.join(struct.pack('>II',*q) for q in points)
        assert data==packed[offset:offset+len(data)],(ordinal,f['ROADSEGID'])
        surf=f['UNPAVSURF'];status=f['PAVSTATUS']
        key=status+'/'+surf+('/bridge' if flags&16 else '')
        summary[key]+=1
        if status=='Unpaved' and surf=='Dirt' and not (flags&24):
            bitset[ordinal>>3]|=1<<(ordinal&7)
        if f['L_STNAME_C'] in ('Walls Rd','Warburton Rd','Old Princetown Rd','New Harmony Rd'):
            name=f['L_STNAME_C']
            routes.setdefault(name,[]).append(dict(ordinal=ordinal,roadsegid=f['ROADSEGID'],nid=f['NID'],surf=surf,status=status,
             endpoints=[[x/1e5-65,y/1e5+45]for x,y in (points[0],points[-1])]))
        offset+=len(data);ordinal+=1
    assert ordinal==count and offset==len(packed)
    s=dict(count=count,stats=summary,dirt=sum(v.bit_count()for v in bitset),packSHA256=m['sha256'],
           bitsetSHA256=hashlib.sha256(bitset).hexdigest(),roadCandidateWit=routes)
    code='''// Generated by tools/geodata/bake-road-surface-types.py. Do not hand edit.
export const NRN_DIRT_SOURCE_SHA256 = '%s';
export const NRN_DIRT_SOURCE_COUNT = %d;
export const NRN_DIRT_SOURCE_BITS = '%s';
'''%(m['sha256'],count,base64.b64encode(bitset).decode())
    return code,s
if __name__=='__main__':
    a=argparse.ArgumentParser(description=__doc__)
    a.add_argument('--source',required=True,type=Path);a.add_argument('--out',type=Path)
    x=a.parse_args()
    code,s=run(x.source,Path(__file__).resolve().parents[2])
    if x.out:x.out.write_text(code)
    print(json.dumps(s,indent=2)+'\n')
