#!/usr/bin/env python3
"""Encode screened roofs in the exact Three.js atlas order and quantized metre frame."""
from collections import Counter,defaultdict
from pathlib import Path
from hashlib import sha256
import argparse,gzip,json,math
import numpy as np

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,required=True);p.add_argument('--root',type=Path,required=True);p.add_argument('--out',type=Path,required=True);p.add_argument('--report',type=Path,required=True)
 o=p.parse_args();src=o.source
 packPath=o.root/'public/world/buildings';idx=json.loads((packPath/'index.json').read_text());data=(packPath/'tiles.pack').read_bytes();store=sha256(data).hexdigest()
 if store != idx['sha256']:raise ValueError('Building source failed atlas intake')
 fits=json.loads((src/'shapes.json').read_text())
 plan=json.loads((src/'sample-plan.json').read_text())
 atlas={r['id']:json.loads(gzip.decompress(data[r['offset']:r['offset']+r['bytes']]))['features'] for r in idx['tiles']}
 rows=defaultdict(list);summary=[];styles=Counter()
 form={'flat':0,'shed':1,'gable':2,'gambrel':3}
 def footprint_key(f):
    h=2166136261
    for pair in f:
      for n in pair:h=((h^round(n*1e6))*16777619)&0xffffffff
    return h
 m=6378137*math.pi/180;f=1-.00669437999014*math.sin(math.radians(46.5))**2
 scale=np.array([m*math.cos(math.radians(46.5))/math.sqrt(f),-m*(1-.00669437999014)/f**1.5]);origin=np.array([-63.2,46.5])
 used=set()
 for c in sorted(fits,key=lambda a:(a['tile'],a['i'])):
    tid,i=c['tile'],c['i'];f=atlas[tid][i]
    F=f['footprint']
    assert F==c['fp'] and not f.get('holes') and (tid,i) not in used,(tid,i)
    used.add((tid,i))
    ring=(np.asarray(F)-origin)*scale
    n=np.asarray(c['axisWorld']);P=np.asarray(c['curve']);slopes=np.diff(P[:,1])/np.diff(P[:,0]);
    family=form[c['kind']]
    steep=max(abs(slopes)) >=.61 and c['width']<18
    style=7 if family==3 or (family==2 and steep) else (8 if family==2 and (c['width']>12 or c['area']>315) else 9)
    p0=ring; p1=np.roll(p0,-1,axis=0); diff=p1-p0
    length=np.linalg.norm(diff,axis=1)
    normalize=lambda a:a/np.maximum(np.linalg.norm(a,axis=1)[:,None],1e-8)
    facing=normalize((p0+p1)*.5-ring.mean(axis=0))
    toward=normalize(np.asarray(c['roadPoint'])-(p0+p1)*.5)
    # Keep decorative closed access details on one qualifying readily seen side only.
    y0=np.interp((p0-ring.mean(axis=0))@n,P[:,0],P[:,1]);y1=np.roll(y0,-1)
    score=(np.sum(facing*toward,axis=1)+.15*np.minimum(length/18,1)+.2*np.minimum(y0,y1)/8)
    score[(length<7.05)|(np.minimum(y0,y1)<2.85)]=-100
    side=int(score.argmax()) if np.max(score)>.26 else -1
    fixed=np.round(P.ravel()*100).astype(int)
    assert -12000<=min(fixed)<=max(fixed)<=15000
    key=footprint_key(F);nx,nz=[round(float(v)*1e6) for v in n]
    fields=[i,key,family,style,side,nx,nz,*map(int,fixed)]
    rows[tid].append(fields)
    summary.append({'tile':tid,'i':i,'kind':c['kind'],'style':style,'side':side,'county':c['county'],'n':c['n'],'nHold':c['nHold'],'p90':c['p90'],'oldP90':c['priorP90'],'sha':c['windowSHA']})
    styles[style]+=1
 compact=lambda o:json.dumps(o,separators=(',',':'))
 source_sha=sha256(compact(summary).encode()).hexdigest()
 generated=("// Generated by tools/geodata/bake-farm-shells.py. Do not edit.\n"
      f"export const FARM_ATLAS_SHA='{store}';\n"
      f"export const FARM_PROFILE_SOURCE_SHA='{source_sha}';\n"
      f"export const FARM_PROFILE_COUNT={len(summary)};\n"
      "export const FARM_PROFILES={\n"+',\n'.join(' '+json.dumps(k)+':'+compact(v) for k,v in rows.items())+"\n} as const;\n")
 o.out.parent.mkdir(exist_ok=True,parents=True);o.out.write_text(generated)
 all_p90=np.array([x['p90'] for x in fits]);old=np.array([x['priorP90'] for x in fits])
 print('Selected',len(summary),'styles',styles,'tiles',len(rows),'source KB',len(generated),'gzip',len(gzip.compress(generated.encode(),mtime=0)))
 print('Holds',sum(x['nHold']for x in fits),'source centres',sum(x['n']for x in fits))
 report={
  'atlasSha256':store,'profileSourceSha256':source_sha,'selectedRoofs':len(summary),'consideredRoofs':len(plan),'tiles':len(rows),
  'nativeRaster':'NRCan CanElevation High Resolution DEM mosaic 10_3-mosaic-1m, DSM and DTM; EPSG:3979 native 1 m grid',
  'nativeDSMUrl':'https://canelevation-dem.s3.ca-central-1.amazonaws.com/hrdem-mosaic-1m/10_3-mosaic-1m-dsm.tif',
  'nativeDTMUrl':'https://canelevation-dem.s3.ca-central-1.amazonaws.com/hrdem-mosaic-1m/10_3-mosaic-1m-dtm.tif',
  'counties':dict(Counter(x['county']for x in fits)),'forms':dict(Counter(x['kind']for x in fits)),'styleSizes':dict(styles),'inspectedSourcePixels':sum(x['n']for x in fits),'blindHoldoutPixels':sum(x['nHold']for x in fits),
  'heldoutP90BuildingMedianM':[float(np.median(old)),float(np.median(all_p90))],
  'heldoutP90UpperP90M':[float(np.quantile(old,.9)),float(np.quantile(all_p90,.9))],
  'shoreOrCollisionChanges':False,
 }
 o.report.parent.mkdir(exist_ok=True,parents=True)
 o.report.write_text(json.dumps(report,indent=2)+'\n')
 (src/'accepted-farm-roofs.json').write_text(compact(summary)+'\n')
if __name__=='__main__':main()
