#!/usr/bin/env python3
"""Bake a conservative, wet-only inset for one existing Charlottetown basin."""
import gzip
import hashlib
import json
import math
from pathlib import Path
import zlib

import numpy as np

ROOT=Path(__file__).resolve().parents[2]
WORLD=ROOT/'public/world'
EVIDENCE=ROOT/'data/odbl/quartermaster/coast.json'
source=json.loads(EVIDENCE.read_text());base=json.loads((WORLD/'cover.json').read_text())
body=(WORLD/base['file']).read_bytes()
if hashlib.sha256(body).hexdigest()!=base['compressedSha256']:raise ValueError('Unexpected province cover')
west,south,east,north=base['bounds'];cw,ch=base['width'],base['height']
coarse=np.frombuffer(gzip.decompress(body),'u1').reshape(ch,cw,2)[:,:,1]
rad=math.pi/180;e2=6.69437999014e-3;f=1-e2*math.sin(46.5*rad)**2
mx=6378137*rad*math.cos(46.5*rad)/math.sqrt(f);mz=6378137*(1-e2)*rad/f**1.5
wx,wz=(west+63.2)*mx,(46.5-north)*mz
dx,dz=(east-west)*mx/cw,(north-south)*mz/ch
ray=np.asarray(source['coast'])
lo,la=ray.T;coast=np.column_stack(((lo+63.2)*mx,(46.5-la)*mz))
def atlas(x,z):
    u=(x-wx)/dx-.5;v=(z-wz)/dz-.5;i,j=np.floor(u).astype(int),np.floor(v).astype(int)
    a,b=u-i,v-j
    return 2*((1-b)*((1-a)*coarse[j,i]+a*coarse[j,i+1])+b*((1-a)*coarse[j+1,i]+a*coarse[j+1,i+1])-128)
mouth=coast[-1]+np.linspace(0,1,2049)[:,None]*(coast[0]-coast[-1])
mouthMax=float(atlas(*mouth.T).max())
if mouthMax>=-2.0:raise ValueError('The derived mouth closure must fit wholly in existing water')
if len(coast)!=22:raise ValueError('Unexpected reviewed bank scope')
# Align every outer edge to the province's sample-centre grid. There the
# coarse marching contour and the refined curtain meet on the same line.
pad=36.
i0,j0=np.floor(((coast.min(axis=0)-pad)-[wx,wz])/[dx,dz]-.5).astype(int)
i1,j1=np.ceil(((coast.max(axis=0)+pad)-[wx,wz])/[dx,dz]-.5).astype(int)
div=64;nx,nz=(i1-i0)*div+1,(j1-j0)*div+1
x0,z0=wx+(i0+.5)*dx,wz+(j0+.5)*dz
x1,z1=wx+(i1+.5)*dx,wz+(j1+.5)*dz
z,x=np.indices((nz,nx))
x=x0+x.ravel()*dx/div;z=z0+z.ravel()*dz/div
ring=np.vstack([coast,coast[0]])
inside=np.zeros(len(x),dtype=bool);squared=np.full(len(x),np.inf)
for (ax,az),(bx,bz) in zip(ring[:-1],ring[1:],strict=True):
    a,b=bx-ax,bz-az
    if b:inside^=((az>z)!=(bz>z))&(x<(z-az)*a/b+ax)
    den=a*a+b*b
    if den:
        r=np.clip(((x-ax)*a+(z-az)*b)/den,0,1)
        squared=np.minimum(squared,(x-ax-a*r)**2+(z-az-b*r)**2)
# A tent's furthest support is hypot(stepX,stepZ); hold beyond it even
# after 25-centimetre quantization to prohibit water outside the source.
inset=math.hypot(dx,dz)/div+.17
sdf=np.sqrt(squared)*np.where(inside,-1,1)+inset
def ramp(start,end,values):
    u=np.clip((values-start)/(end-start),0,1)
    return u*u*(3-2*u)
edge=np.minimum.reduce([x-x0,x1-x,z-z0,z1-z])
# The signed-distance blend on dry banks is also bounded, but is never a
# land classifier in its own right: runtime only takes min(original, local).
weight=ramp(10.,24.,edge)*(1-ramp(12.,27.,sdf))
r=np.rint(np.clip(sdf*4+128,0,255)).astype('u1')
g=np.rint(weight*255).astype('u1');r[g==0]=128
data=np.column_stack([r,g]).tobytes()
blob=bytearray(gzip.compress(data,mtime=0,compresslevel=9));blob[9]=255
asset='harbour/odbl/v1/quartermaster-coast.rg.gz';target=WORLD/asset;target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(blob)
old=atlas(x,z);local=.25*(r.astype(float)-128)
new=old+g/255*(np.minimum(old,local)-old)
added=(old>=0)&(new<0)
result=dict(id='quartermaster-coast-v1',asset=asset,boundsXZ=[x0,z0,x1,z1],baseGridIJ=[int(i0),int(j0),int(i1),int(j1)],
            width=int(nx),height=int(nz),divisions=div,cellMetres=[dx/div,dz/div],outwardFadeStartM=10,outwardFadeEndM=24,
            sourceInsetM=round(inset,6),mouthMaxLegacyM=round(mouthMax,6),addedWetSampleCentres=int(np.count_nonzero(added)),
            addedWetApproxM2=round(float(np.count_nonzero(added))*dx*dz/(div*div),1),decodedBytes=len(data),compressedBytes=len(blob),
            crc32=f'{zlib.crc32(data):08x}',sha256=hashlib.sha256(data).hexdigest(),
            sourceSha256=hashlib.sha256(EVIDENCE.read_bytes()).hexdigest(),pinCoverSha256=base['compressedSha256'])
(ROOT/'src/sim/quartermaster.generated.ts').write_text('// Generated by tools/terrain/bake-quartermaster-coast.py.\nexport const QUARTERMASTER = '+json.dumps(result,indent=2)+' as const;\n')
print(json.dumps(result,indent=2))
