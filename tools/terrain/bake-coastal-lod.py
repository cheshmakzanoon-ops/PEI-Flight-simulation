#!/usr/bin/env python3
"""Bake a crack-free, error-bounded distant topology for the two surveyed windows.

No rescaling, land classification, new height samples or remote data. Candidate
triangles may meet the fine reference at integer grid vertices or the centres
where opposite diagonals cross. Test both; their union contains every vertex
of the intersection of both continuous piecewise affine surfaces.
"""
import base64
import gzip
import hashlib
import json
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parents[2]
TOL_CM=9
BLOCK=16
# At depth 8 the candidate is a single fine half-cell. Permit one final split
# at its centre: alternating right triangles can oppose the reference diagonal.
DEPTH=9

def plan(values,nx,nz):
    width=2*nx-1
    idx=lambda x,z:z*width+x
    def height(p):
        x,z=p%width,p//width
        k=(z//2)*nx+x//2
        if x%2 and z%2:
            return .5*(values[k+nx]+values[k+1])  # actual NE–SW reference edge
        assert x%2==z%2==0
        return values[k]
    levels=[[] for _ in range(DEPTH)]
    def inspect(a,b,c,depth):
        m=(a+b)//2
        if depth==DEPTH:
            return
        ax,az,bx,bz,cx,cz=a%width,a//width,b%width,b//width,c%width,c//width
        ha,hb,hc=height(a),height(b),height(c)
        max_error=abs(height(m)-.5*(ha+hb))
        if depth<DEPTH-1:
            sx,sz,tx,tz=bx-ax,bz-az,cx-ax,cz-az
            det=sx*tz-sz*tx
            for zz in range(min(az,bz,cz),max(az,bz,cz)+1):
                start=min(ax,bx,cx);start+=(start-zz)%2
                for xx in range(start,max(ax,bx,cx)+1,2):
                    dx,dz=xx-ax,zz-az
                    u,v=(dx*tz-dz*tx)/det,(sx*dz-sz*dx)/det
                    if min(u,v,1-u-v)>=0:
                        max_error=max(max_error,abs(height(idx(xx,zz))-ha-u*(hb-ha)-v*(hc-ha)))
        x,z=m%width,m//width
        boundary=x in (0,2*nx-2) or z in (0,2*nz-2)
        levels[depth].append((a,b,c,m,(c+a)//2,(b+c)//2,max_error,boundary))
        inspect(c,a,m,depth+1);inspect(b,c,m,depth+1)
    for z in range(0,nz-1,BLOCK):
        for x in range(0,nx-1,BLOCK):
            nw,ne,sw,se=(idx(2*(x+dx),2*(z+dz)) for dx,dz in ((0,0),(BLOCK,0),(0,BLOCK),(BLOCK,BLOCK)))
            inspect(sw,ne,nw,0);inspect(ne,sw,se,0)
    splits=set()
    for level in reversed(levels):
        # An edge midpoint belongs to BOTH adjacent triangles. Propagate
        # children/forced exterior edges upward so no neighbouring T-junction remains.
        for _,_,_,m,left,right,err,boundary in level:
            if err>TOL_CM or boundary or left in splits or right in splits:
                splits.add(m)
    bits=[];decided=set();triangles=0
    def emit(a,b,c,depth):
        nonlocal triangles
        m=(a+b)//2
        if depth<DEPTH:
            if m not in decided:
                bits.append(int(m in splits))
                decided.add(m)
            if m in splits:
                emit(c,a,m,depth+1);emit(b,c,m,depth+1)
                return
        triangles+=1
    for a,b,c,*_ in levels[0]:
        emit(a,b,c,0)
    packed=bytearray((len(bits)+7)//8)
    for n,bit in enumerate(bits):
        packed[n>>3]|=bit<<(n&7)
    return bytes(packed),len(bits),triangles

def main():
    generated={}
    for site,nx,nz in [('east-point',129,145),('west-point',145,129)]:
        raw=gzip.decompress((ROOT/f'public/world/coastal/v1/{site}.i16.gz').read_bytes())
        values=struct.unpack(f'<{nx*nz}h',raw)
        b,nb,tri=plan(values,nx,nz)
        generated[site]=dict(nx=nx,nz=nz,sha256=hashlib.sha256(raw).hexdigest(),
                             bits=nb,triangles=tri,stream=base64.b64encode(b).decode('ascii'))
        print(site,tri,'triangles;',len(b),'decision bytes')
    (ROOT/'src/render/coastal-lod.generated.ts').write_text(
        '// Generated by tools/terrain/bake-coastal-lod.py; bit order is documented in coastal-lod.ts.\n'
        +'export const DISTANT_COAST = '+json.dumps(generated,indent=2)+' as const;\n')
if __name__=='__main__':
    main()
