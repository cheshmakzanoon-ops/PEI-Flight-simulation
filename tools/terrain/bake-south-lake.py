#!/usr/bin/env python3
"""Rasterize a bounded photometric mask, not a new shore, water surface or simulator level."""
import gzip
import hashlib
import json
import math
from pathlib import Path
import zlib

import numpy as np

ROOT=Path(__file__).resolve().parents[2]
WORLD=ROOT/'public/world'
EVIDENCE=ROOT/'data/sheltered-water/south-lake-nhn.json'
source=json.loads(EVIDENCE.read_text())
cover_spec=json.loads((WORLD/'cover.json').read_text())
cover_gz=(WORLD/cover_spec['file']).read_bytes()
if hashlib.sha256(cover_gz).hexdigest()!=cover_spec['compressedSha256']:
    raise ValueError('Current cover hash does not match its manifest')
west,south,east,north=cover_spec['bounds']
cw,ch=cover_spec['width'],cover_spec['height']
cover=np.frombuffer(gzip.decompress(cover_gz),'u1').reshape(ch,cw,2)[:,:,1]
origin_lon,origin_lat=-63.2,46.5
rad=math.pi/180;e2=6.69437999014e-3;p=origin_lat*rad;f=1-e2*math.sin(p)**2
mx=6378137*rad*math.cos(p)/math.sqrt(f);mz=6378137*(1-e2)*rad/f**1.5
lon,lat=np.asarray(source['ring']).T
world=np.stack([(lon-origin_lon)*mx,(origin_lat-lat)*mz],axis=1)
anchor=np.floor(world[:-1].mean(axis=0))
theta=35*rad;c,s=math.cos(theta),math.sin(theta)
rotate=np.array([[c,-s],[s,c]])
polygon=(world-anchor)@rotate.T
step=4.0
left,top=np.floor(polygon.min(axis=0)/step)*step-2*step
right,bottom=np.ceil(polygon.max(axis=0)/step)*step+2*step
width,height=int((right-left)/step),int((bottom-top)/step)
t,u=np.indices((height,width));x=left+(u.ravel()+.5)*step;z=top+(t.ravel()+.5)*step
inside=np.zeros(len(x),dtype=bool);nearest=np.full(len(x),np.inf)
for (ax,az),(bx,bz) in zip(polygon[:-1],polygon[1:],strict=True):
    dx,dz=bx-ax,bz-az
    if dz:
        inside^=((az>z)!=(bz>z))&(x<(z-az)*dx/dz+ax)
    k=dx*dx+dz*dz
    if k:
        p=np.clip(((x-ax)*dx+(z-az)*dz)/k,0,1)
        nearest=np.minimum(nearest,(x-ax-p*dx)**2+(z-az-p*dz)**2)
edge=np.sqrt(nearest)
# A bilinear tent extends one full texel in each direction; require its
# entire (rotated) support to be inside the official feature, not just centres.
buffer=step*math.sqrt(2)+.30
candidates=np.where(inside&(edge>buffer))[0]
wx,wz=(np.stack([x[candidates],z[candidates]],axis=1)@rotate+anchor).T
lu=(origin_lon+wx/mx-west)/(east-west)*cw-.5;lv=(north-(origin_lat-wz/mz))/(north-south)*ch-.5
def sample(xx,yy):
    i,j=np.floor(xx).astype(int),np.floor(yy).astype(int)
    if min(i.min(),j.min())<0 or i.max()>=cw-1 or j.max()>=ch-1:raise ValueError('Outside cover')
    a,b=xx-i,yy-j
    return (1-b)*((1-a)*cover[j,i]+a*cover[j,i+1])+b*((1-a)*cover[j+1,i]+a*cover[j+1,i+1])
# Bound each rotated tent by an axis-aligned box. Include its intersections
# with the cover lattice, so checking bilinear cell corners is sufficient.
R=step*(abs(c)+abs(s))+.08
rx=R/mx/(east-west)*cw;rz=R/mz/(north-south)*ch
if rx>=.5 or rz>=.5:raise ValueError('Cover extents changed; revisit conservative corner test')
lo,hi=lu-rx,lu+rx;low,high=lv-rz,lv+rz
max_cover=np.full(len(wx),-np.inf)
for uu in (lo,hi,np.clip(np.ceil(lo),lo,hi)):
    for vv in (low,high,np.clip(np.ceil(low),low,high)):
        max_cover=np.maximum(max_cover,sample(uu,vv))
water=candidates[max_cover<127.98]
fade=np.clip((edge[water]-buffer)/(21.-buffer),0,1)
image=np.zeros(len(x),'u1');image[water]=np.rint(255*fade**2*(3-2*fade)).astype('u1')
raw=image.tobytes();blob=bytearray(gzip.compress(raw,mtime=0,compresslevel=9));blob[9]=255
asset='water/v1/south-lake.r8.gz';path=WORLD/asset;path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(blob)
pad=2*step
aabb=[math.floor(n) for n in (world[:,0].min()-pad,world[:,1].min()-pad)]+[math.ceil(n) for n in (world[:,0].max()+pad,world[:,1].max()+pad)]
out=dict(id='south-lake-v1',asset=asset,width=width,height=height,texelMetres=step,boundsXZ=aabb,worldAnchorXZ=anchor.tolist(),
         rotatedBoundsXZ=[left,top,right,bottom],rotationCS=[round(c,12),round(s,12)],insetMetres=round(buffer,5),
         fullShelterInsetMetres=21,activeTexels=int(np.count_nonzero(image)),decodedBytes=len(raw),
         compressedBytes=len(blob),crc32=f'{zlib.crc32(raw):08x}',sha256=hashlib.sha256(raw).hexdigest(),
         polygonSHA256=hashlib.sha256(EVIDENCE.read_bytes()).hexdigest(),coverSHA256=cover_spec['compressedSha256'])
(ROOT/'src/render/south-lake.generated.ts').write_text('// Generated by tools/terrain/bake-south-lake.py.\nexport const SOUTH_LAKE = '
    +json.dumps(out,indent=2)+' as const;\n')
print(json.dumps(out,indent=2))
