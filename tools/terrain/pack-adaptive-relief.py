#!/usr/bin/env python3
"""Pack guarded 16 m measured surfaces for independent read-only HTTP range streams."""
import argparse,gzip,hashlib,json,struct
from pathlib import Path
import numpy as np
hash_=lambda a:hashlib.sha256(a).hexdigest()
def pack(source:Path,out:Path,world:Path,ts:Path|None):
    out.mkdir(parents=True,exist_ok=True)
    terrain=json.loads((world/'terrain.json').read_text())
    cover=json.loads((world/'cover.json').read_text())
    road=json.loads((world/'roads.json').read_text())
    buildings=json.loads((world/'buildings/index.json').read_text())
    hedge=(world/'woodland/hedgerows-v1/index.json').read_bytes()
    pins=dict(terrain=terrain['sha256'],cover=cover['compressedSha256'],road=road['sha256'],buildings=buildings['sha256'],hedges=hash_(hedge))
    tiles=[];packs=[];block=bytearray()
    def flush():
        if not block:return
        name=f'relief-{len(packs):02d}.pack'
        (out/name).write_bytes(block)
        packs.append(dict(file=name,bytes=len(block),sha256=hash_(block)));block.clear()
    ordered=sorted(source.glob('*.bin'),key=lambda path:tuple(map(int,path.stem.split('-')))[::-1])
    for path in ordered:
        raw=path.read_bytes()
        assert len(raw)==1568+385*385*2
        mask=raw[:1568];h=np.frombuffer(raw[1568:],'<i2').reshape(385,385)
        occupancy=np.unpackbits(np.frombuffer(mask,'u1'),bitorder='little').reshape(112,112)
        assert not occupancy[0,:].any() and not occupancy[-1,:].any() and not occupancy[:,0].any() and not occupancy[:,-1].any()
        q=np.diff(h,axis=1,prepend=np.zeros((385,1),dtype=np.int16)).astype('<i2')
        payload=mask+q.tobytes();compressed=gzip.compress(payload,7,mtime=0)
        if len(block)+len(compressed)>540000:flush()
        tiles.append(dict(id=path.stem,pack=len(packs),offset=len(block),bytes=len(compressed),
            cells=int(occupancy.sum()),sha256=hash_(payload),archiveSha256=hash_(compressed)))
        block.extend(compressed)
    flush()
    plan=dict(version=1,encoding='guard-bitset-i16le-row-delta-dm',cols=32,rows=22,intervals=384,parentIntervals=112,bounds=terrain['bounds'],
      pins=pins,license='https://open.canada.ca/en/open-government-licence-canada',bytes=sum(p['bytes'] for p in packs),packs=packs,tiles=tiles)
    text=json.dumps(plan,separators=(',',':'))+'\n'
    (out/'index.json').write_text(text)
    if ts is not None:
        ts.write_text('// Generated by tools/terrain/pack-adaptive-relief.py.\n'
            +f"export const RELIEF_INDEX_SHA='{hash_(text.encode())}';\n")
    print(len(tiles),sum(q['cells'] for q in tiles),len(packs),plan['bytes'])
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('source',type=Path);p.add_argument('out',type=Path);p.add_argument('world',type=Path)
    p.add_argument('--ts',type=Path)
    args=p.parse_args();pack(args.source,args.out,args.world,args.ts)
