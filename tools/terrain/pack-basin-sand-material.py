#!/usr/bin/env python3
"""Build linear relative luminance, tangent normals and AO from a pinned CC0 sand scan."""
from pathlib import Path
from PIL import Image
import argparse, gzip, hashlib, json, zlib
import numpy as np
NAME='basin-sand-scan.rgba.gz'
S=352
SOURCE={
    'diff': '5b849983d08fda1c6d28b95b55851c2227697598721b25ff2b85e57cf8b04fc4',
    'nor_gl': '0133712fbe5de7389948150a6900a687707b93df4e6652b531b6e317b49737b3',
    'ao': '5a814b7486c2e7fab80f905ba041d0af07879377578d6c47ec379a24e9ecdb6b',
}
sha=lambda b:hashlib.sha256(b).hexdigest()

def pack(source,out,generated):
    def read(key):
        p=source/(key+'.jpg')
        assert sha(p.read_bytes())==SOURCE[key]
        return np.asarray(Image.open(p).convert('RGB').resize((S,S),Image.Resampling.LANCZOS))/255.
    base=read('diff')
    light=np.where(base<=.04045,base/12.92,((base+.055)/1.055)**2.4)
    l=light@np.array([.2126,.7152,.0722])
    # Preserve only local detail. The texture must not color this PEI site
    # with the unknown substrate from the generic scan's capture location.
    relative=np.clip((l/np.median(l)-1)*.60+.5,0,1)
    n=read('nor_gl');s=np.sqrt(np.maximum(.0001,np.sum((2*n-1)**2,axis=2)))
    nx=(2*n[:,:,0]-1)/s
    nz=-(2*n[:,:,1]-1)/s  # north-facing GL V to world south/positive image row
    ao=read('ao')[:,:,0]
    raw=np.rint(255*np.stack([relative,nx*.5+.5,nz*.5+.5,ao],axis=2)).astype('uint8').tobytes()
    b=bytearray(gzip.compress(raw,9,mtime=0));b[9]=255
    out.mkdir(parents=True,exist_ok=True);(out/NAME).write_bytes(b)
    stamp=dict(asset='ground/basin-head/v1/'+NAME,decodedBytes=len(raw),width=S,height=S,bytes=len(b),
        sha256=sha(raw),compressedSha256=sha(b),crc32=f'{zlib.crc32(raw):08x}',
        source='https://polyhaven.com/a/aerial_beach_01',license='https://creativecommons.org/publicdomain/zero/1.0/',
        sourceSha256=SOURCE,nominalSourceWidthMetres=30)
    generated.write_text('// Generated by tools/terrain/pack-basin-sand-material.py.\nexport const BASIN_SCAN='+json.dumps(stamp,indent=2)+' as const;\n')
    print(json.dumps(stamp,indent=2))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('source',type=Path);p.add_argument('out',type=Path)
    p.add_argument('generated',type=Path);a=p.parse_args();pack(a.source,a.out,a.generated)
