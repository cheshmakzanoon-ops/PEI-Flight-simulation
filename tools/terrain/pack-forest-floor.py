#!/usr/bin/env python3
"""Pack two licensed stock soil/sprig surface maps without acquiring location imagery."""
import argparse,hashlib,json
from pathlib import Path
import numpy as np
from PIL import Image
sha=lambda b:hashlib.sha256(b).hexdigest()
KEYS=('forrest_ground_01','forrest_ground_03')
def pack(src,records,out,ts):
    raw=json.loads(records.read_text())
    if isinstance(raw,dict):
        raw=[dict(a,asset=q['id'],local=q['id']+'-'+a['kind']+'.jpg') for q in raw['assets'] for a in q['raw']]
    out.mkdir(parents=True,exist_ok=True)
    assets=[]
    for idx,asset in enumerate(KEYS):
        fields={t['kind']:t for t in raw if t['asset']==asset}
        def channel(kind,mode):
            f=src/fields[kind]['local'];assert sha(f.read_bytes())==fields[kind]['sha256']
            return np.asarray(Image.open(f).convert(mode).resize((384,384),Image.Resampling.LANCZOS)).astype(float)/255
        col=channel('Diffuse','RGB')
        lin=np.where(col<.04045,col/12.92,((col+.055)/1.055)**2.4)
        y=lin@np.array([.2126,.7152,.0722])
        log=np.log(y+.017)
        a=channel('AO','L');g=channel('nor_gl','RGB')
        data=np.dstack((.5+np.clip(log-np.median(log),-.69,.69)*.7,g[:,:,0],g[:,:,1],a))
        rgba=np.round(np.clip(data*255,0,255)).astype('uint8')
        file='duff-'+str(idx+1)+'.webp'
        Image.fromarray(rgba,'RGBA').save(out/file,'WEBP',lossless=True,method=6,exact=True)
        assert np.array_equal(np.asarray(Image.open(out/file)),rgba)
        assets.append(dict(id=asset,page='https://polyhaven.com/a/'+asset,author='Rob Tuytel',
          licence='https://creativecommons.org/publicdomain/zero/1.0/',widthMetres=2,
          raw=[{k:v for k,v in q.items() if k not in ('asset','local')} for q in fields.values()],
          file=file,bytes=(out/file).stat().st_size,sha256=sha((out/file).read_bytes())))
    (out/'sources.json').write_text(json.dumps(dict(encoding='384 lossless RGBA; R normalized log luminance, G/B source tangent normal, A ambient occlusion',assets=assets),indent=2)+'\n')
    ts.write_text('// Generated by tools/terrain/pack-forest-floor.py.\nexport const FOREST_FLOOR_ASSETS='
        +json.dumps([{k:r[k] for k in ('file','bytes','sha256')} for r in assets],separators=(',',':'))+' as const;\n')
    print([(q['file'],q['bytes']) for q in assets])
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for field in ('src','receipt','out','ts'):p.add_argument(field,type=Path)
    args=p.parse_args();pack(args.src,args.receipt,args.out,args.ts)
